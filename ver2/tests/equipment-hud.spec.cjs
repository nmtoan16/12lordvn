const {test,expect}=require('@playwright/test');
const fs=require('node:fs');
const {equipmentBattle,hit,heal,captureBattle,renderOneFrame}=require('./helpers/equipment-battle.cjs');
test.use({actionTimeout:10000});
test('Actual combat HUD: initial barrier, absorb, break, heal and paused frame',async({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const frame=await equipmentBattle(page,[1,2,5]);
  await page.click('#pause');await expect.poll(()=>frame.evaluate(()=>LoanV2.state().paused)).toBe(true);
  const initial=await frame.evaluate(()=>LoanV2.state().battle);
  expect(initial.maxHP).toBe(105);expect(initial.barrier).toBe(52);
  await expect(frame.getByRole('meter',{name:'Lá chắn'})).toHaveAttribute('aria-valuenow','52');
  await expect(frame.locator('.v2-hud')).toHaveClass(/v2-golden/);
  fs.mkdirSync('analysis/verification/ver2',{recursive:true});
  await captureBattle(page,frame,'analysis/verification/ver2/hud-barrier-start.png');
  await hit(frame,20);
  expect(await frame.evaluate(()=>LoanV2.state().battle.barrier)).toBe(38);
  expect(await frame.evaluate(()=>LoanV2.state().battle.fighters[0].hp)).toBe(105);
  await expect(frame.getByRole('meter',{name:'Lá chắn'})).toHaveAttribute('aria-valuenow','38');
  await renderOneFrame(page);
  await captureBattle(page,frame,'analysis/verification/ver2/hud-barrier-absorb.png');
  await hit(frame,80);
  expect(await frame.evaluate(()=>LoanV2.state().battle.barrier)).toBe(0);
  expect(await frame.evaluate(()=>LoanV2.state().battle.fighters[0].hp)).toBe(87);
  await expect(frame.locator('.v2-barrier')).toBeHidden();
  await renderOneFrame(page);
  await captureBattle(page,frame,'analysis/verification/ver2/hud-barrier-break.png');
  await heal(frame,10);
  expect(await frame.evaluate(()=>LoanV2.state().battle.fighters[0].hp)).toBe(105);
  const events=await frame.evaluate(()=>equipmentBattleFixture.events);
  expect(events).toEqual(expect.arrayContaining([expect.objectContaining({type:'block',amount:14,side:0}),expect.objectContaining({type:'damage',amount:18,side:0}),expect.objectContaining({type:'heal',amount:18,side:0}),expect.objectContaining({type:'barrier-break',side:0})]));
  await page.click('#resume');await page.waitForTimeout(90);await page.click('#pause');
  await captureBattle(page,frame,'analysis/verification/ver2/hud-heal-floating.png');
  const frozen=await frame.locator('.v2-vfx').evaluate(c=>c.toDataURL());
  await page.waitForTimeout(500);
  expect(await frame.locator('.v2-vfx').evaluate(c=>c.toDataURL())).toBe(frozen);
  expect(errors).toEqual([]);
  fs.writeFileSync('analysis/verification/ver2/hud-events.json',JSON.stringify({initial,events},null,2));
});
